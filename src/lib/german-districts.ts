export function getDistricts(cityName: string): string[] {
  const normalized = cityName.trim().toLowerCase();
  for (const [city, districts] of Object.entries(CITY_DISTRICTS)) {
    if (city.toLowerCase() === normalized) {
      return districts;
    }
  }
  return [];
}

export function getSearchVariants(keyword: string, city: string): string[] {
  const districts = getDistricts(city);
  const variants: string[] = [`${keyword} ${city}`];
  for (const district of districts) {
    variants.push(`${keyword} ${city}-${district}`);
  }
  return variants;
}
